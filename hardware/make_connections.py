#!/usr/bin/env python3
"""
Builds docs/connections.md: one table per device listing every pin, the net it
sits on, and what else is on that net.  Derived from the schematic files via
validate_sheets.py, so it cannot drift from the design.
"""
import collections, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate_sheets as V

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "docs", "connections.md")

SHEET_OF = {"Main.kicad_sch": "Microcontroller", "USB_UART.kicad_sch": "USB / UART",
            "Power.kicad_sch": "Power", "LED.kicad_sch": "LED chain",
            "LED Butterfly.kicad_sch": "Root"}

DEVICE_NOTES = {
    "ESP32-C3FH4": "Bare QFN-32 MCU. 4 MB internal flash, so the six SPI flash pins are no-connects.",
    "U5": "USB to UART bridge. Runs from 5 V VBUS and regulates its own 3.3 V I/O.",
    "U2": "Li-ion charge controller. I_REG(mA) = 1000 / R_PROG(kOhm); 24 kOhm gives ~42 mA.",
    "U3": "3.3 V LDO for the MCU only. EN tied to VIN so SW1 kills it.",
    "U4": "USB ESD protection. Pins 1/6 are one node, 3/4 are the other.",
    "J1": "USB-C receptacle. Both halves of the data pair are tied so the cable can go in either way up.",
    "Q1": "Pulls CHIP_ENABLE for esptool's auto-reset.",
    "Q2": "Pulls BOOT for esptool's auto-reset.",
    "SW1": "SPDT slide switch, surface mount. Pin 2 is the common terminal.",
    "BT1a": "LIR2032 ONLY. A CR2032 here is a fire risk.",
    "BT1b": "LIR2032 ONLY. A CR2032 here is a fire risk.",
}

ORDER = ["ESP32-C3FH4", "U5", "U4", "J1", "Q1", "Q2", "U2", "U3", "SW1",
         "BT1a", "BT1b", "D1", "D2", "D3", "D4", "D5", "D6", "D7"]


def collect():
    pins = {}      # (sheet, ref, num) -> (name, net)
    nets = collections.defaultdict(list)
    for f in V.SHEETS:
        p = os.path.join(V.PROJ, f)
        if not os.path.exists(p):
            continue
        _prob, named, _refs = V.analyse(p)
        for net, members in named.items():
            for ref, num, pname in members:
                if ref.startswith("#"):
                    continue
                pins[(f, ref, num)] = (pname, net)
                nets[net].append((ref, num))
        for (sheet, ref, num), pname in V.NC_PINS.items():
            if sheet == f:
                pins.setdefault((f, ref, num), (pname, "__NC__"))
    return pins, nets


def pinkey(n):
    m = re.match(r"(\d+)", n)
    return (0, int(m.group(1)), "") if m else (1, 0, n)


def main():
    pins, nets = collect()
    by_ref = collections.defaultdict(list)
    sheet_of_ref = {}
    for (f, ref, num), (pname, net) in pins.items():
        by_ref[ref].append((num, pname, net))
        sheet_of_ref[ref] = SHEET_OF.get(f, f)

    refs = [r for r in ORDER if r in by_ref]
    refs += sorted(r for r in by_ref if r not in refs)

    with open(OUT, "w") as fh:
        fh.write("# Pin-by-pin connections\n\n"
                 "Every pin of every active device, the net it sits on, and what else is on\n"
                 "that net. Generated by `hardware/make_connections.py` from the schematic\n"
                 "files, so it cannot drift from the design. Passive two-pin parts are listed\n"
                 "in the net summary at the bottom rather than getting a table each.\n\n"
                 "Net names follow the design's conventions exactly: `CHIP_ENABLE`, `BOOT`,\n"
                 "`LED_DATA`, `UART_RX`/`UART_TX` (named from the MCU's point of view),\n"
                 "`VBUS`, `VBAT`, `VBAT_SW`, `FT_3V3`, `+3.3V`, `GND`.\n\n"
                 "---\n\n")
        for ref in refs:
            rows = sorted(by_ref[ref], key=lambda r: pinkey(r[0]))
            if len(rows) <= 2 and not ref.startswith("D"):
                continue
            fh.write(f"## {ref} — {sheet_of_ref.get(ref,'')}\n\n")
            note = DEVICE_NOTES.get(ref)
            if note:
                fh.write(f"{note}\n\n")
            fh.write("| Pin | Name | Net | Goes to |\n|---|---|---|---|\n")
            for num, pname, net in rows:
                others = [f"{r}.{p}" for r, p in sorted(nets[net]) if r != ref]
                if net == "__NC__":
                    net_disp, goes = "—", "**no connect**"
                elif net.startswith("<unnamed"):
                    net_disp = "*(local)*"
                    goes = ", ".join(others) if others else "—"
                else:
                    net_disp = f"`{net}`"
                    goes = ", ".join(others) if others else "—"
                if len(goes) > 70:
                    goes = goes[:67] + "…"
                fh.write(f"| {num} | {pname or '~'} | {net_disp} | {goes} |\n")
            fh.write("\n")

        fh.write("---\n\n## Every net\n\n| Net | Pins on it |\n|---|---|\n")
        for net in sorted(nets, key=lambda s: (s.startswith("<"), s)):
            if net.startswith("<unnamed"):
                continue
            conn = ", ".join(f"{r}.{p}" for r, p in sorted(nets[net]))
            fh.write(f"| `{net}` | {conn} |\n")
    print(f"wrote {OUT} — {len(refs)} devices, {len(nets)} nets")


if __name__ == "__main__":
    main()
